// savedStarts reads every start saved in chunk (cx, cz).
func savedStarts(worldDir string, cx, cz int) []mcworld.Start {
	r, err := mcworld.OpenRegion(filepath.Join(worldDir, "region", fmt.Sprintf("r.%d.%d.mca", cx>>5, cz>>5)))
	if err != nil {
		return nil
	}
	c, _ := r.Chunk(cx&31, cz&31)
	if c == nil {
		return nil
	}
	var out []mcworld.Start
	for _, st := range c.Starts() {
		if len(st.Pieces) > 0 {
			out = append(out, st)
		}
	}
	return out
}

// scenePiecesMatched counts saved piece boxes an assembled scene's piece
// boxes reproduce (code-built structures, whose pieces are not jigsaw).
func scenePiecesMatched(saved []mcworld.Piece, sc *structure3d.Scene) int {
	want := map[[6]int]int{}
	for _, p := range saved {
		want[[6]int{int(p.BB[0]), int(p.BB[1]), int(p.BB[2]), int(p.BB[3]), int(p.BB[4]), int(p.BB[5])}]++
	}
	ok := 0
	for _, p := range sc.Pieces {
		k := [6]int{p.Min[0], p.Min[1], p.Min[2], p.Max[0], p.Max[1], p.Max[2]}
		if want[k] > 0 {
			want[k]--
			ok++
		}
	}
	return ok
}

// sceneStartEra finds the era whose store and terrain rebuild a saved
// code-built start (shipwreck, ocean ruin, monument, mineshaft, ruined
// portal), preferring the chunk's terrain era. A chunk saved before its
// terrain step keeps the pieces' placeholder Y (shipwrecks and ocean ruins
// at 90) until features run, which will use the current install: there only
// the horizontal boxes are compared and the answer is era 0.
//
// rebuilt reports whether any era assembled the start at all; a rebuild
// that assembles but matches no era is a wrong prediction, not an unknown.
// firstStore, when set, is the already open store of era first.
func (s *Service) sceneStartEra(ctx context.Context, m *EraMap, rootID, versionID, world string, st mcworld.Start, seed int64, first int, firstStore *structure3d.Store) (era int, matched, rebuilt bool) {
	proto := !savedChunkFull(m.worldDir, st.ChunkX, st.ChunkZ)
	order := []int{first}
	for e := range m.Eras {
		if e != first {
			order = append(order, e)
		}
	}
	if proto {
		order = []int{0}
	}
	for _, e := range order {
		store, owned := firstStore, false
		if e != first || store == nil {
			var err error
			if store, err = s.StructureAssetStoreEra(rootID, versionID, world, m.Eras[e].Without); err != nil {
				continue
			}
			owned = true
		}
		closeStore := func() {
			if owned {
				store.Close()
			}
		}
		smp, err := s.EraSampler(ctx, rootID, versionID, world, e)
		if err != nil {
			closeStore()
			continue
		}
		const dim = "minecraft:overworld"
		info, _ := smp.TerrainInfo(dim)
		height := func(x, z int) int {
			if h, ok := smp.TerrainSurfaceAt(dim, x, z); ok {
				return h
			}
			return info.SeaLevel
		}
		sc, err := structure3d.AssembleTerrain(store, st.ID, seed, st.ChunkX*16, st.ChunkZ*16, structure3d.OverworldHeight, samplerTerrain(smp, dim, info, height))
		closeStore()
		if err != nil || sc == nil {
			return 0, false, rebuilt // generated by code we do not run
		}
		if len(sc.Pieces) > 0 {
			rebuilt = true // only real piece boxes make a mismatch meaningful
		}
		pieces := sc.Pieces
		if len(pieces) == 0 && len(sc.Blocks) > 0 && len(st.Pieces) == 1 {
			pieces = []structure3d.PieceBox{{Min: sc.Min, Max: sc.Max}}
		}
		if scenePiecesMatchedXZ(st.Pieces, pieces, proto) == len(st.Pieces) && len(pieces) == len(st.Pieces) {
			return e, true, true
		}
		// An undecorated start chunk still holds the box postProcess resets.
		if proto && len(sc.StartPieces) > 0 && scenePiecesMatchedXZ(st.Pieces, sc.StartPieces, proto) == len(st.Pieces) && len(sc.StartPieces) == len(st.Pieces) {
			return e, true, true
		}
	}
	return 0, false, rebuilt
}

// savedChunkFull reports whether chunk (cx, cz) finished generating.
func savedChunkFull(worldDir string, cx, cz int) bool {
	r, err := mcworld.OpenRegion(filepath.Join(worldDir, "region", fmt.Sprintf("r.%d.%d.mca", cx>>5, cz>>5)))
	if err != nil {
		return false
	}
	c, _ := r.Chunk(cx&31, cz&31)
	if c == nil {
		return false
	}
	status, _ := c.Root["Status"].(string)
	return status == "minecraft:full" || status == "full"
}

// scenePiecesMatchedXZ is scenePiecesMatched over piece boxes, ignoring Y
// when xzOnly.
func scenePiecesMatchedXZ(saved []mcworld.Piece, got []structure3d.PieceBox, xzOnly bool) int {
	key := func(b [6]int) [6]int {
		if xzOnly {
			b[1], b[4] = 0, 0
		}
		return b
	}
	want := map[[6]int]int{}
	for _, p := range saved {
		want[key([6]int{int(p.BB[0]), int(p.BB[1]), int(p.BB[2]), int(p.BB[3]), int(p.BB[4]), int(p.BB[5])})]++
	}
	ok := 0
	for _, p := range got {
		k := key([6]int{p.Min[0], p.Min[1], p.Min[2], p.Max[0], p.Max[1], p.Max[2]})
		if want[k] > 0 {
			want[k]--
			ok++
		}
	}
	return ok
}

// samplerTerrain is the noise-stage world of smp for the code-built
// structure adapters: base columns (cached), both surface heights and the
// noise biome.
func samplerTerrain(smp *LocalSampler, dim string, info SeedMapTerrainInfo, height structure3d.HeightFunc) structure3d.ModTerrain {
	type col struct {
		sub           []TerrainSubstance
		solidTop, top int
	}
	cols := map[[2]int]*col{}
	get := func(x, z int) *col {
		c := cols[[2]int{x, z}]
		if c == nil {
			c = &col{sub: make([]TerrainSubstance, info.Height)}
			c.solidTop, c.top, _ = smp.TerrainColumn(dim, x, z, c.sub)
			cols[[2]int{x, z}] = c
		}
		return c
	}
	return structure3d.ModTerrain{
		Height:   height,
		SeaLevel: info.SeaLevel,
		Ground: func(x, y, z int) structure3d.GroundKind {
			i := y - info.MinY
			c := get(x, z)
			if i < 0 || i >= len(c.sub) {
				if i < 0 {
					return structure3d.GroundSolid
				}
				return structure3d.GroundAir
			}
			switch c.sub[i] {
			case TerrainSolid:
				return structure3d.GroundSolid
			case TerrainWater, TerrainLava:
				return structure3d.GroundLiquid
			}
			return structure3d.GroundAir
		},
		Column: func(x, z int) (int, int) { c := get(x, z); return c.solidTop, c.top },
		Biome: func(x, y, z int) string {
			b, _ := smp.BiomeAt(dim, x, y, z)
			return b
		},
	}
}
