func TranslateCategory(en bool, cat string) string {
	raw := strings.TrimSpace(cat)
	if raw == "" {
		return ""
	}
	if en {
		return raw
	}
	key := strings.ToLower(raw)
	if v, ok := zhCategories[key]; ok {
		return v
	}
	return raw
}
